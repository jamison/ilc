struct OsRandom;

impl rand_core::RngCore for OsRandom {
    fn next_u32(&mut self) -> u32 {
        let mut buf = [0u8; 4];
        self.fill_bytes(&mut buf);
        u32::from_be_bytes(buf)
    }

    fn next_u64(&mut self) -> u64 {
        let mut buf = [0u8; 8];
        self.fill_bytes(&mut buf);
        u64::from_be_bytes(buf)
    }

    fn fill_bytes(&mut self, dest: &mut [u8]) {
        getrandom(dest).expect("getrandom failed");
    }

    fn try_fill_bytes(&mut self, dest: &mut [u8]) -> Result<(), rand_core::Error> {
        getrandom(dest).map_err(rand_core::Error::new)
    }
}

impl rand_core::CryptoRng for OsRandom {}

/// Deterministic RNG matching Phase 838a pq_keygen key derivation.
///
/// The Phase 1431 manifest public keys were generated with pq_keygen_838a.v0.1,
/// which uses this SeedRng wrapper. Any change to this implementation would
/// produce a different public key and break the manifest cross-check.
/// Do not replace with `keygen_from_seed()` or any other derivation.
struct SeedRng {
    seed: [u8; 32],
    counter: u64,
    buffer: [u8; 48],
    pos: usize,
}

impl SeedRng {
    fn new(seed: &[u8; 32]) -> Self {
        let mut rng = SeedRng {
            seed: *seed,
            counter: 0,
            buffer: [0u8; 48],
            pos: 48,
        };
        rng.refill();
        rng
    }

    fn refill(&mut self) {
        let counter_bytes = self.counter.to_be_bytes();
        self.buffer = sha2_384(&[&self.seed, &counter_bytes]);
        self.counter += 1;
        self.pos = 0;
    }
}

impl rand_core::RngCore for SeedRng {
    fn next_u32(&mut self) -> u32 {
        let mut buf = [0u8; 4];
        self.fill_bytes(&mut buf);
        u32::from_be_bytes(buf)
    }

    fn next_u64(&mut self) -> u64 {
        let mut buf = [0u8; 8];
        self.fill_bytes(&mut buf);
        u64::from_be_bytes(buf)
    }

    fn fill_bytes(&mut self, dest: &mut [u8]) {
        let mut written = 0;
        while written < dest.len() {
            if self.pos >= self.buffer.len() {
                self.refill();
            }
            let available = self.buffer.len() - self.pos;
            let needed = dest.len() - written;
            let n = available.min(needed);
            dest[written..written + n].copy_from_slice(&self.buffer[self.pos..self.pos + n]);
            self.pos += n;
            written += n;
        }
    }

    fn try_fill_bytes(&mut self, dest: &mut [u8]) -> Result<(), rand_core::Error> {
        self.fill_bytes(dest);
        Ok(())
    }
}

impl rand_core::CryptoRng for SeedRng {}

