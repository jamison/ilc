def _run_cli(*args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, "-m", "ilc_core.cli", *args],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        check=False,
        timeout=30,
    )


def _generated_config(tmp_path: Path) -> Path:
    result = generate_node_init_material(
        root=tmp_path / "node",
        network_id="ilc-rc01",
        host="203.0.113.10",
        grpc_port=50151,
        quic_port=7101,
        allow_test_stub_crypto=True,
    )
    return result.config_path


def _write_config(path: Path, *, grpc_endpoint: str = "203.0.113.10:50151", grpc_listen: str = "0.0.0.0:50151", p2p_listen: str = "0.0.0.0:7101", public_endpoint: str = "203.0.113.10:7101") -> Path:
    path.write_text(
        "\n".join(
            [
                "[network]",
                'network_id = "ilc-rc01"',
                "",
                "[grpc]",
                f'grpc_listen_addr = "{grpc_listen}"',
                "",
                "[p2p]",
                f'p2p_listen_addr = "{p2p_listen}"',
                f'public_endpoint = "{public_endpoint}"',
                "",
                "[validator]",
                f'grpc_endpoint = "{grpc_endpoint}"',
                "",
            ]
        ),
        encoding="utf-8",
    )
    return path


def _cli_payload(result: subprocess.CompletedProcess[str]) -> dict[str, object]:
    assert result.returncode == 0, result.stderr
    payload = json.loads(result.stdout)
    assert isinstance(payload, dict)
    return payload


def _plan_output(payload: dict[str, object]) -> str:
    data = payload.get("data")
    assert isinstance(data, dict)
    output = data.get("output")
    assert isinstance(output, str)
    return output


def test_firewall_plan_help_discoverable() -> None:
    result = _run_cli("node", "firewall-plan", "--help")

    assert result.returncode == 0
    assert "--provider" in result.stdout
    assert "--source-mode" in result.stdout
    assert "--output" in result.stdout


def test_firewall_plan_generic_output(tmp_path: Path) -> None:
    config_path = _generated_config(tmp_path)

    plan = build_firewall_plan(config_path=config_path, provider="generic")
    payload = json.loads(plan.output)

    assert payload["provider"] == "generic"
    assert {"port": 50151, "protocol": "tcp", "direction": "inbound", "purpose": "ilc-node gRPC ingress"} in payload["port_table"]
    assert {"port": 7101, "protocol": "udp", "direction": "inbound", "purpose": "ilc-node QUIC/P2P"} in payload["port_table"]


