def test_firewall_plan_advisory_present_in_all_formats(tmp_path: Path) -> None:
    config_path = _generated_config(tmp_path)

    for provider in ("digitalocean", "generic", "ufw"):
        output = build_firewall_plan(config_path=config_path, provider=provider).output
        assert "gRPC is mTLS-authenticated" in output
        assert "Peer-authenticated proposal ingress" in output
        assert "nc -z -w 3 203.0.113.10 50151" in output
        assert "HTTP/2 over TCP fallback" in output or "HTTP/2 TCP fallback" in output


def test_firewall_plan_output_written_atomically(tmp_path: Path) -> None:
    config_path = _generated_config(tmp_path)
    output_path = tmp_path / "plans" / "firewall.json"

    result = _run_cli(
        "node",
        "firewall-plan",
        "--config",
        str(config_path),
        "--provider",
        "digitalocean",
        "--output",
        str(output_path),
    )

    payload = _cli_payload(result)
    data = payload["data"]
    assert isinstance(data, dict)
    assert data["wrote_output_path"] == str(output_path)
    assert output_path.is_file()
    assert json.loads(output_path.read_text(encoding="utf-8"))["inbound_rules"]
    assert list(output_path.parent.glob("*.tmp")) == []


def test_firewall_plan_cli_generic_json_first(tmp_path: Path) -> None:
    config_path = _generated_config(tmp_path)

    result = _run_cli("node", "firewall-plan", "--config", str(config_path))
    payload = _cli_payload(result)

    assert payload["command"] == "node firewall-plan"
    assert payload["ok"] is True
    output = _plan_output(payload)
    assert json.loads(output)["provider"] == "generic"


def test_firewall_plan_tomllib_fallback_parses_generated_config(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    config_path = _generated_config(tmp_path)

    monkeypatch.setattr(firewall_plan_runtime, "tomllib", None)

    payload = json.loads(build_firewall_plan(config_path=config_path, provider="generic").output)

    assert payload["network_id"] == "ilc-rc01"
    assert {"port": 50151, "protocol": "tcp", "direction": "inbound", "purpose": "ilc-node gRPC ingress"} in payload["port_table"]


def test_firewall_plan_tomllib_fallback_rejects_malformed_value(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    config_path = tmp_path / "node_config.toml"
    config_path.write_text('[network]\nnetwork_id = "unterminated\n', encoding="utf-8")
    monkeypatch.setattr(firewall_plan_runtime, "tomllib", None)

    with pytest.raises(ValueError, match="node_firewall_config_invalid_toml"):
        build_firewall_plan(config_path=config_path, provider="generic")


