def test_firewall_plan_source_modes_require_ips(tmp_path: Path) -> None:
    config_path = _generated_config(tmp_path)

    with pytest.raises(ValueError, match="node_firewall_validator_ips_required"):
        build_firewall_plan(config_path=config_path, source_mode="validator-set")

    with pytest.raises(ValueError, match="node_firewall_controller_ip_required"):
        build_firewall_plan(config_path=config_path, source_mode="controller-only", validator_ips="1.2.3.4")


